"""Write the test signal and the expected model output as C++ headers.

The input is a sine, the output is what the model makes of it on the reference
path: model_forward.onnx in ONNX Runtime, the state carried by hand from a zero
start. Embedding both keeps the C++ steps free of file IO.

Usage:
    uv run scripts/make_test_data.py [--model models/model_forward.onnx] [--blocks 8] [--out steps/common/assets]
"""

import argparse
import pathlib

import numpy as np
import onnxruntime as ort

ROOT = pathlib.Path(__file__).resolve().parent.parent
BLOCK = 2048
SAMPLE_RATE = 44100
FREQUENCY = 220.0

HEADER = """\
// Generated by scripts/make_test_data.py — do not edit.
#pragma once

#include <array>
#include <cstddef>
{extra_include}
{length_constant}

{doc}
// clang-format off
inline constexpr std::array<float, k_signal_length> {name} = {{
{samples}
}};
// clang-format on
"""

INPUT_DOC = """\
// The signal the steps run through the model: a {frequency:g} Hz sine at half scale,
// {blocks} blocks of {block} samples at 44.1 kHz, one channel, laid out end to end."""

TARGET_DOC = """\
// The output the model should produce for the sine in test_signal.h: {blocks} blocks
// of {block} samples. Generated by running the model in Python, and what the C++
// steps are checked against."""


def sine(length, amplitude=0.5):
    t = np.arange(length, dtype=np.float64) / SAMPLE_RATE
    return (amplitude * np.sin(2 * np.pi * FREQUENCY * t)).astype(np.float32)


def run_reference(model_path, signal):
    """Block by block, state carried by hand: what the C++ OnnxEngine does."""
    session = ort.InferenceSession(str(model_path), providers=["CPUExecutionProvider"])
    state_input = session.get_inputs()[1]
    state = np.zeros(state_input.shape, dtype=np.float32)
    out = []
    for begin in range(0, len(signal), BLOCK):
        block = signal[begin:begin + BLOCK].reshape(1, 1, BLOCK)
        audio, state = session.run(None, {"audio": block, "state_in": state})
        out.append(audio.ravel())
    return np.concatenate(out).astype(np.float32)


def as_float_literal(value):
    """`0` is not a float literal in C++, `0.0f` is."""
    text = f"{value:.9g}"
    if "." not in text and "e" not in text and "n" not in text:
        text += ".0"
    return text + "f"


def as_rows(samples, per_row=8, indent="    "):
    rows = []
    for start in range(0, len(samples), per_row):
        row = ", ".join(as_float_literal(value) for value in samples[start:start + per_row])
        rows.append(indent + row + ",")
    return "\n".join(rows)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--model", type=pathlib.Path, default=ROOT / "models/model_forward.onnx")
    parser.add_argument("--blocks", type=int, default=8)
    parser.add_argument("--out", type=pathlib.Path, default=ROOT / "steps/common/assets")
    args = parser.parse_args()

    audio_in = sine(args.blocks * BLOCK)
    audio_out = run_reference(args.model, audio_in)

    common = dict(blocks=args.blocks, block=BLOCK)
    length_constant = f"\nconstexpr size_t k_signal_length = {args.blocks * BLOCK};\n"

    for name, doc, samples, filename, extra_include, length in (
        ("k_input_signal", INPUT_DOC.format(frequency=FREQUENCY, **common), audio_in,
         "test_signal.h", "", length_constant),
        ("k_target_output_signal", TARGET_DOC.format(**common), audio_out,
         "target_signal.h", '\n#include "common/assets/test_signal.h"  // k_signal_length\n', ""),
    ):
        path = args.out / filename
        path.write_text(HEADER.format(doc=doc, name=name, samples=as_rows(samples),
                                      extra_include=extra_include, length_constant=length))
        print(f"{args.blocks} blocks of {BLOCK} samples -> {path}")
    for i in range(args.blocks):
        block = audio_out[i * BLOCK:(i + 1) * BLOCK]
        print(f"  target block {i}: peak {np.abs(block).max():.4f} rms {np.sqrt((block ** 2).mean()):.4f}")


if __name__ == "__main__":
    main()
